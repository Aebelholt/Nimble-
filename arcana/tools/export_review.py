#!/usr/bin/env python3
"""Write analysis/cards_review.md: every card with status keep, five-part format."""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
cards = json.loads((ROOT / "data/sejr_arcana.json").read_text())
out = ["# Reworked cards\n", "Generated by `tools/export_review.py` from `data/sejr_arcana.json`. Cards still at status `review` are not listed.\n"]
for c in cards:
    if c["status"] != "keep":
        continue
    r = c["resource"]
    out.append(f"## {c['name']}\n\n`{c['id']}` · {c['tier']}" + (f" · {c['class']}" if c['class'] else "") + "\n")
    out.append("**Object.** " + c["object"] + "\n")
    out.append("**Unlock.**\n" + "\n".join("- " + u for u in c["unlock"]) + ("\n- Risk: " + c["risk"] if c["risk"] else "") + "\n")
    out.append(f"**Resource: {r['name']} ({r['type']}).** " + r["text"] + "\n")
    out.append("**Powers.**\n" + "\n".join("- " + p for p in c["powers"]) + "\n")
    out.append("**Escalation.** " + c["escalation"] + "\n")
    out.append("*Changelog:* " + c["notes"] + "\n")
(ROOT / "analysis/cards_review.md").write_text("\n".join(out))
print("written")
