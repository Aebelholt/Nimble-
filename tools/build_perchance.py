#!/usr/bin/env python3
"""Regenerate data/sejr_arcana_perchance.txt from data/sejr_arcana.json.

Keeps the structure of the original module: other_arcanum, arcana_data, arcanum_line,
the forge lists and functions (copied verbatim from sources/), and adds class_arcanum_name
so the hero card can look up a class arcanum by class.
Cut cards are left out.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
cards = [c for c in json.loads((ROOT / "data/sejr_arcana.json").read_text()) if c["status"] != "cut"]
orig = (ROOT / "sources/sejr_arcana_perchance_original.txt").read_text()
found = [c for c in cards if c["kind"] == "found"]
klass = [c for c in cards if c["kind"] == "class"]


def js(s):
    return json.dumps(s, ensure_ascii=False)


def entry(c):
    tier = c["tier"] if c["kind"] == "found" else "Class"
    return (f'  {js(c["name"])}: {{tier:{js(tier)}, obj:{js(c["object"])}, unlock:{js(c["unlock"])}, '
            f'risk:{js(c["risk"])}, res:{js(c["resource"]["text"])}, power:{js("<br>".join(c["powers"]))}, '
            f'esc:{js(c["escalation"])}}}')


head = """// ==========================================
// SEJR ARCANA MODULE (for the Sejr fork of the Shadowdark generator)
// LISTS PANEL: replace your old other_arcanum list with everything below.
// It uses d(n) and sec(title, body), which the fork already defines.
// Generated by tools/build_perchance.py from data/sejr_arcana.json. Edit the JSON, not this file.
// ==========================================

other_arcanum
""" + "\n".join("  " + c["name"] for c in found) + """

// ---------- CURATED CARDS ----------

arcana_data() =>
  return {
""" + ",\n".join(entry(c) for c in found + klass) + """
  };

// Class name (as in hero_class) to its class arcanum.
class_arcanum_name() =>
  return {
""" + ",\n".join(f'  {js(c["class"])}: {js(c["name"])}' for c in klass) + """
  };

// Player sees the object. GM opens the fold. Ritual boxes are for absent-player ticks.
arcanum_line(name) =>
  let a = arcana_data()[name];
  if (!a) return "<p><b>Arcanum:</b> " + name + ", unexamined.</p>";
  let boxes = a.unlock.map(u => "<li>&#9744; " + u + "</li>").join("");
  let g = "<ul>" + boxes + "</ul>";
  if (a.risk) g += "<p><b>Risk:</b> " + a.risk + "</p>";
  if (a.res) g += "<p><b>Resource:</b> " + a.res + "</p>";
  if (a.power) g += "<p><b>Power:</b> " + a.power + "</p>";
  if (a.esc) g += "<p><b>Escalation:</b> " + a.esc + "</p>";
  g += "<p><b>Examine:</b> " + forge_clue.evaluateItem + "</p>";
  return "<p><b>Arcanum:</b> " + name + " (" + a.tier + "), unexamined. " + a.obj + "</p><details><summary>GM: ritual and powers</summary>" + g + "</details>";

"""

start = orig.index("// ---------- FORGED ARCANA")
tail = orig[start:]
tail = tail.replace(
    "// ==========================================\n// HERO CARD EDIT: in your hero function, swap this line",
    "// ==========================================\n// HERO CARD EDIT: in your hero function, swap this line\n"
    '//   let arc = d(6) <= 4 ? "the " + cls + " class arcanum" : other_arcanum.evaluateItem;\n'
    "// for\n"
    "//   let arc = d(6) <= 4 ? class_arcanum_name()[cls] : other_arcanum.evaluateItem;\n"
    "// and swap this line")
out = ROOT / "data/sejr_arcana_perchance.txt"
out.write_text(head + tail)
print(out, len(found), "found +", len(klass), "class cards")
