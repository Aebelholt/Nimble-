#!/usr/bin/env python3
"""Generate a diversity matrix from data/sejr_arcana.json (matrix blocks).

Usage: make_matrix.py [output path]. analysis/matrix.md is the Step 1 snapshot of the
rebuilt set before any rework; write later runs to another path (analysis/matrix_after.md).
The cluster and gap text below describes the Step 1 set.
"""
import json, pathlib, collections, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
cards = json.loads((ROOT / "data/sejr_arcana.json").read_text())


def cell(s):
    return (s or "").replace("|", "/")


rows = []
for n, c in enumerate(cards, 1):
    m = c["matrix"]
    kind = c["class"] if c["kind"] == "class" else "found"
    origin = m["origin"] + (f" ({m['mythology']})" if m.get("mythology") else "")
    rt = m["resource_type"] + (f" ({m['max']})" if m.get("max") else "")
    rows.append(f"| {n} | {cell(c['name'])} | {kind} | {m['tier']} | {cell(rt)} | "
                f"{cell(m['refill'])} | {cell(m['power'])} | {cell(m['cost'])} | "
                f"{cell(origin)} | {cell(m['look'])} |")

found = [c for c in cards if c["kind"] == "found"]
cnt = lambda key, pool=found: collections.Counter(c["matrix"][key] for c in pool)
rt = cnt("resource_type")
unplaced = sum(1 for c in found if c["matrix"]["region"] == "Unspecified")

out = f"""# Diversity matrix

Generated by `tools/make_matrix.py` from `data/sejr_arcana.json`. {len(cards)} cards: {len(cards) - len(found)} class, {len(found)} found.
The original 44-card JSON was not available (see CHANGELOG.md), so this covers the 36 cards that could be rebuilt from the uploads.

Origin column cites the setting where the card names one. A value of "unspecified" means the card text names no place, faction or culture.

| # | Card | Class | Tier | Resource type | Refill activity | Power category | Cost type | Culture or origin | Material and look |
|---|------|-------|------|---------------|-----------------|----------------|-----------|-------------------|-------------------|
""" + "\n".join(rows) + f"""

## Counts (found pool, {len(found)} cards)

- Resource type: {", ".join(f"{k} {v}" for k, v in rt.most_common())}.
- Origin not placed in the setting: {unplaced} of {len(found)}.
- Tier: {", ".join(f"{k} {v}" for k, v in cnt("tier").most_common())}.

## Clusters

1. **Pip-tracker monoculture.** {rt["pip tracker"]} of {len(found)} found cards are a plain pip tracker. Only one found card is a d6 accumulation tracker (Valkyrie's Feather), one is Wound-cost (Bonded Relic, and it spends Hit Dice), one is a toggle (Oath-Band), one is session-bound (Rune Fragment).
2. **Six armors.** Tide-Coat, Sul Hide, Pitch-Sap Harness, Ossuary Mail, Hellhide, Kettle Plate. All defense, all worn, all fill a body slot. Five of six use the form "Armor N+DEX"; Nimble heroes have Defense, and armor as a damage filter belongs to monsters (rules/nimble_core_rules_3.2.txt, Armor & Defense, Monsters). Hellhide gives no Defense value at all.
3. **Death and Wound cheating.** Valkyrie's Feather, Binding Linens, Hollow Vessel, Sul Hide (Mend), Rusted Spear (Spare, Mend), Hourglass of Borrowed Time (undo a roll). Class cards add Berserker (Death's Door) and Shepherd (Toll). Eight cards solve "I would go down" in the same slot.
4. **Mythology lifted straight from real-world sources.** Valkyrie's Feather (Norse valkyrie), Rune Fragment (Elder Futhark names: Fehu, Algiz, Raido, Uruz, Tiwaz, Ansuz, Eihwaz, Sowilo), Sown Teeth (Cadmus and the Spartoi), Binding Linens (Egyptian mummification, myrrh, hieroglyphs), Rusted Spear (Telephus healed by Achilles' spear rust), Axe of Nine Eyes (Odin and Argus), Hexing Needles (witch poppets), Fairy Jar (European folk fairy).
5. **Passive or rest refills.** Forgotten Key (Safe Rest only), Bonded Relic (Hit Dice, Safe Rest), Rune Fragment (once per episode), Kettle Plate (stoke for ten minutes, no sourcing), Pitch-Sap Harness (prying, but it finishes on a Safe Rest). Class cards Shepherd, Songweaver, Commander and Berserker fill from the class's own best actions or clear at rest.
6. **Closed loop.** Hexing Needles regains Thread by unpicking a hex that Thread paid for.
7. **No place of origin.** {unplaced} of {len(found)} found cards name no setting location, faction or culture. The spec requires the object to name a place, maker or prior owner.
8. **Wounds as the default price.** Wounds or Wound-like loss appear as the cost on Forgotten Key, Black Lotus, Hollow Vessel, Sul Hide, Hellhide, Rusted Spear, Bonded Relic and, among class cards, Mage, Shepherd and Zephyr.
9. **Duplicate resource names.** Resonance (Forgotten Key, Bell of the Three Sisters), Debt (Unpaid Favor, Hollow Contract), Hunger (Sul Hide, and the Wolf Pelt cited in the spec).
10. **Missing sections.** Drowning Scale is a stub ("See the homebrew document"). Ossuary Mail and Hellhide have no power that spends the resource. Bonded Relic has no unlock deed ("None. It chose you") and a generic object.

## Gaps

- **Origins.** No found card comes from the Revlend Marshes, the Doorish Hills or the Deadlands (only the Stormshifter and Hunter class cards touch them), the Cliffs of the Dead, the Endless Warrens, or any world beyond the arches (Deathreach, Drakeholm, Drendaan, Eruwynd, Io, Korax, Maphotar, Terrache, Threska, Vynan, Arkus; setting/13_worlds_beyond_the_arches.md). No card belongs to the Seekers of the Sun, the Golden Knights, the Children of Ibraxus, the Knights of the Nameless King or the Black Hand beyond the Cheat's die.
- **Power categories.** Social has three cards, information three, mobility two. There is no ranged or battlefield-control item, almost no ally support (Valkyrie's Feather, Rune Fragment's Tiwaz), and no item that matters in downtime or travel.
- **Resource shapes.** Few d6 accumulation trackers, one session-bound ritual (Rune Fragment), and no tracker that fills by an out-of-combat activity other than a chore (hunt, confession, craft, pilgrimage, trade).
- **Refill activities.** Missing: hunting, confessing, trading, ferrying someone through an arch, teaching, mapping, repairing, performing, tending a grave. The pool leans on "bury someone", "feed it" and "clean it".
- **Looks.** Six worn armors, several jars and cases (Fairy Jar, Hollow Vessel, Black Lotus Case, the Sul Hide tank), three weapons (Axe, Apology Blade, Rusted Spear). No instrument among the found cards, no tool, no vehicle, no animal companion, no book or map.
"""
(ROOT / "analysis").mkdir(exist_ok=True)
target = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "analysis/matrix.md"
target.write_text(out)
print(target, "written")
